"""DEV tool (run 2): print the Postgres DDL for the pilot's tables and indexes, converted from
the schema the current code creates in SQLite. Used once to write the baseline Alembic migration
(backend/migrations/versions/0001_pilot_baseline.py), whose SQL is then reviewed and frozen; it
is not run at deploy time. Triggers are NOT converted here -- they are hand-written PL/pgSQL in
the migration.

    python -m scripts.pg_schema_from_sqlite > /tmp/pilot_tables.sql
"""

from __future__ import annotations

import re
import sqlite3
import tempfile
from pathlib import Path

# The workflow tables the pilot reads and writes (identity, claims, approval, the rule store).
SHARED_TABLES = ("provider_claims", "physician_owner_scopes", "physician_referral_preferences",
                 "physician_identity_selections", "physician_onboarding_events")


PILOT_SCHEMA_MODULES = ("store.py", "assistant.py")  # every module that creates pilot tables


def pilot_tables() -> set[str]:
    root = Path(__file__).resolve().parents[1] / "backend" / "pilot"
    found: set[str] = set()
    for name in PILOT_SCHEMA_MODULES:
        found |= set(re.findall(r"CREATE TABLE IF NOT EXISTS ([a-z_]+)", (root / name).read_text(encoding="utf-8")))
    return found | {"practice_invitations"} | set(SHARED_TABLES)


def convert_table(sql: str, keep: set[str]) -> str:
    name = re.match(r"CREATE TABLE (?:IF NOT EXISTS )?\"?([a-z_]+)\"?", sql).group(1)
    body = sql[sql.index("(") + 1: sql.rindex(")")]
    # Drop `--` comments first: joining a definition onto one line would otherwise turn the
    # column after a comment into part of the comment (it happened to agent_prepared_items).
    body = "\n".join(line.split("--", 1)[0] for line in body.splitlines())
    out = []
    for part in _split_top_level(body):
        line = " ".join(part.split())
        line = re.sub(r"\bINTEGER PRIMARY KEY AUTOINCREMENT\b", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", line)
        line = re.sub(r"^(\w+) INTEGER PRIMARY KEY\b", r"\1 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", line)
        line = re.sub(r"\bREAL\b", "DOUBLE PRECISION", line)
        line = re.sub(r"\bINTEGER\b", "BIGINT", line)  # SQLite integers are 64-bit
        # A foreign key to a table the pilot schema doesn't carry (demo-only) is dropped.
        ref = re.search(r"REFERENCES (\w+)\s*\(\w+\)", line)
        if ref and ref.group(1) not in keep:
            line = line.replace(ref.group(0), "").strip()
        out.append(line)
    # Insertion order (the code orders ties by SQLite's implicit rowid); hidden from query results.
    out.insert(0, "_rowid BIGINT GENERATED ALWAYS AS IDENTITY")
    return f"CREATE TABLE {name} (\n  " + ",\n  ".join(out) + "\n);"


def _split_top_level(body: str) -> list[str]:
    parts, depth, current = [], 0, ""
    for char in body:
        depth += char == "("
        depth -= char == ")"
        if char == "," and depth == 0:
            parts.append(current.strip())
            current = ""
        else:
            current += char
    if current.strip():
        parts.append(current.strip())
    return parts


def main() -> None:
    from backend.pilot.store import PilotStore
    from backend.workflow import WorkflowStore

    keep = pilot_tables()
    with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as directory:
        path = Path(directory) / "schema.sqlite"
        PilotStore(workflow=WorkflowStore(path))
        from backend.pilot.assistant import _SCHEMA as ASSISTANT_SCHEMA

        db = sqlite3.connect(path)
        db.executescript(ASSISTANT_SCHEMA)
        rows = db.execute("SELECT type, name, tbl_name, sql FROM sqlite_master WHERE sql IS NOT NULL "
                          "AND type IN ('table', 'index') ORDER BY type DESC, rowid").fetchall()
        db.close()
    tables = [row for row in rows if row[0] == "table" and row[2] in keep]
    indexes = [row for row in rows if row[0] == "index" and row[2] in keep]
    print(f"-- {len(tables)} tables, {len(indexes)} indexes")
    for _kind, _name, _table, sql in tables:
        print(convert_table(sql, keep))
    for _kind, _name, _table, sql in indexes:
        print(" ".join(sql.split()) + ";")


if __name__ == "__main__":
    main()
